-- Football V2 stage access and prospective public-stage selection.
-- Apply once in the Supabase SQL Editor before deploying the companion functions.

ALTER TABLE public.football_v2_shadow_stage_snapshots
  ADD COLUMN IF NOT EXISTS availability_evidence jsonb,
  ADD COLUMN IF NOT EXISTS lineup_evidence jsonb;

CREATE TABLE IF NOT EXISTS public.football_v2_rollout_settings (
  id boolean PRIMARY KEY DEFAULT true CHECK (id),
  pilot_account text NOT NULL DEFAULT 'google_2d3cef6b6e2d',
  all_members_enabled boolean NOT NULL DEFAULT false,
  public_stage text NOT NULL DEFAULT 't10'
    CHECK (public_stage IN ('t10', 't2', 't15')),
  public_stage_effective_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.football_v2_rollout_settings (id)
VALUES (true)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.football_v2_public_stage_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage text NOT NULL CHECK (stage IN ('t10', 't2', 't15')),
  effective_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (stage, effective_at)
);

INSERT INTO public.football_v2_public_stage_history (stage, effective_at)
SELECT public_stage, public_stage_effective_at
FROM public.football_v2_rollout_settings
WHERE id = true
  AND NOT EXISTS (SELECT 1 FROM public.football_v2_public_stage_history);

CREATE TABLE IF NOT EXISTS public.football_v2_stage_member_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account text NOT NULL,
  fixture_id bigint NOT NULL,
  stage text NOT NULL CHECK (stage IN ('t2', 't15')),
  claim_state text NOT NULL DEFAULT 'processing'
    CHECK (claim_state IN ('processing', 'claimed')),
  fixture_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  result_data jsonb,
  model_version text,
  created_at timestamptz NOT NULL DEFAULT now(),
  claimed_at timestamptz,
  UNIQUE (account, fixture_id, stage)
);

CREATE INDEX IF NOT EXISTS football_v2_stage_member_claims_account_fixture_idx
  ON public.football_v2_stage_member_claims (account, fixture_id, created_at DESC);

ALTER TABLE public.football_v2_rollout_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.football_v2_public_stage_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.football_v2_stage_member_claims ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.football_v2_rollout_settings FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.football_v2_public_stage_history FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.football_v2_stage_member_claims FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.football_v2_rollout_settings TO service_role;
GRANT SELECT, INSERT ON public.football_v2_public_stage_history TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.football_v2_stage_member_claims TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.football_v2_public_stage_history_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.football_v2_stage_member_claims_id_seq TO service_role;

COMMENT ON TABLE public.football_v2_stage_member_claims IS
  'Idempotent per-member claims for Football V2 T-2 and T-15 stage snapshots; T-10 remains on the existing analysis flow.';

COMMENT ON TABLE public.football_v2_public_stage_history IS
  'Prospective public-stage cutovers. Each verified fixture uses the stage active at its kickoff time, so later switches do not rewrite prior public records.';

CREATE OR REPLACE FUNCTION public.update_football_v2_rollout_settings(
  p_all_members_enabled boolean DEFAULT NULL,
  p_public_stage text DEFAULT NULL
)
RETURNS SETOF public.football_v2_rollout_settings
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  current_row public.football_v2_rollout_settings%ROWTYPE;
  changed_at timestamptz := now();
BEGIN
  IF p_public_stage IS NOT NULL AND p_public_stage NOT IN ('t10', 't2', 't15') THEN
    RAISE EXCEPTION 'invalid_public_stage';
  END IF;

  SELECT * INTO current_row
  FROM public.football_v2_rollout_settings
  WHERE id = true
  FOR UPDATE;

  IF NOT FOUND THEN
    INSERT INTO public.football_v2_rollout_settings (id)
    VALUES (true)
    RETURNING * INTO current_row;
  END IF;

  IF p_public_stage IS NOT NULL AND p_public_stage <> current_row.public_stage THEN
    INSERT INTO public.football_v2_public_stage_history (stage, effective_at)
    VALUES (p_public_stage, changed_at);
  END IF;

  UPDATE public.football_v2_rollout_settings
  SET all_members_enabled = COALESCE(p_all_members_enabled, all_members_enabled),
      public_stage = COALESCE(p_public_stage, public_stage),
      public_stage_effective_at = CASE
        WHEN p_public_stage IS NOT NULL AND p_public_stage <> current_row.public_stage
          THEN changed_at
        ELSE public_stage_effective_at
      END,
      updated_at = changed_at
  WHERE id = true
  RETURNING * INTO current_row;

  RETURN NEXT current_row;
END;
$$;

REVOKE ALL ON FUNCTION public.update_football_v2_rollout_settings(boolean, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.update_football_v2_rollout_settings(boolean, text) TO service_role;
